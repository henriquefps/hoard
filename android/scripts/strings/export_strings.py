#!/usr/bin/env python3
"""Hoard 1's i18next strings as Android resources for the native app (ADR 0019, phase 2b).

The Files side of Hoard 2 says what Hoard 1 says, in both languages: this script turns the keys of
src/i18n/locales/{en,pt-BR}.json (every namespace; culling came in phase 2c) into
native/src/main/res/values{,-pt-rBR}/strings_hoard1.xml.

    python3 android/scripts/strings/export_strings.py           # from the repository root
    python3 android/scripts/strings/export_strings.py --check   # fail if the committed files differ

Rules:
- `browse.newFolder` becomes `t_browse_new_folder` (the `t_` prefix keeps them apart from the native-only strings).
- `{{name}}` interpolations become positional `%N$s` arguments, numbered by first appearance in the English text;
  each string carries a comment with the order (`args: 1=count, 2=name`). Every argument is a string: the caller
  formats numbers and sizes.
- `key_one` / `key_other` become `<plurals>`; the quantity is `count`. pt-BR also gets `many` (CLDR), as `other`.
- A key missing in pt-BR is written in English there too, so lint's MissingTranslation never fails.
"""
import argparse
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[3]
LOCALES = ROOT / "src/i18n/locales"
RES = ROOT / "android/native/src/main/res"
SKIP: set = set()
PLURAL = re.compile(r"^(.*)_(zero|one|two|few|many|other)$")
VAR = re.compile(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}")


def flatten(obj, prefix=""):
    for key, value in obj.items():
        if isinstance(value, dict):
            yield from flatten(value, f"{prefix}{key}.")
        else:
            yield f"{prefix}{key}", value


def snake(key):
    parts = re.split(r"[.\-]", key)
    out = []
    for p in parts:
        p = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", p)
        out.append(p.lower())
    return "t_" + "_".join(out)


def android_text(text, order):
    def sub(m):
        return f"%{order.index(m.group(1)) + 1}$s"

    value = VAR.sub(sub, text)
    value = escape(value).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if value.startswith("@") or value.startswith("?"):
        value = "\\" + value
    # A literal % that is not an argument.
    value = re.sub(r"%(?!\d+\$s)", "%%", value)
    return value


def collect(locale):
    data = json.loads((LOCALES / f"{locale}.json").read_text(encoding="utf-8"))
    return {k: v for k, v in flatten(data) if k.split(".")[0] not in SKIP and isinstance(v, str)}


def build(en, pt):
    singles, plurals = {}, {}
    for key in en:
        m = PLURAL.match(key)
        if m:
            plurals.setdefault(m.group(1), {})[m.group(2)] = key
        else:
            singles[key] = key
    return singles, plurals


def render(locale_strings, en, singles, plurals, orders, quantities=("one", "other")):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by android/scripts/strings/export_strings.py from src/i18n/locales. Do not edit. -->",
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,TypographyEllipsis,TypographyDashes,PluralsCandidate,StringFormatCount,ImpliedQuantity">',
    ]
    names = set()
    for key in sorted(singles):
        name = snake(key)
        if name in names:
            sys.exit(f"duplicate resource name {name}")
        names.add(name)
        order = orders[key]
        text = locale_strings.get(key, en[key])
        comment = f"  <!-- args: {', '.join(f'{i + 1}={v}' for i, v in enumerate(order))} -->" if order else ""
        formatted = ' formatted="false"' if "%" in text and not order else ""
        lines.append(f'    <string name="{name}"{formatted}>{android_text(text, order)}</string>{comment}')
    for base in sorted(plurals):
        name = snake(base)
        if name in names:
            sys.exit(f"duplicate resource name {name}")
        names.add(name)
        forms = plurals[base]
        order = orders[base]
        comment = f"  <!-- args: {', '.join(f'{i + 1}={v}' for i, v in enumerate(order))} -->" if order else ""
        lines.append(f'    <plurals name="{name}">{comment}')
        for quantity in quantities:
            key = forms.get(quantity) or forms.get("other")
            text = locale_strings.get(f"{base}_{quantity}") or locale_strings.get(f"{base}_other") or en[forms.get("other") or key]
            lines.append(f'        <item quantity="{quantity}">{android_text(text, order)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    en = collect("en")
    pt = collect("pt-BR")
    singles, plurals = build(en, pt)
    orders = {}
    for key in singles:
        names = []
        for text in (en[key], pt.get(key, "")):
            for v in VAR.findall(text):
                if v not in names:
                    names.append(v)
        orders[key] = names
    for base, forms in plurals.items():
        names = []
        for key in sorted(forms.values()):
            for text in (en[key], pt.get(key, "")):
                for v in VAR.findall(text):
                    if v not in names:
                        names.append(v)
        orders[base] = names
    outputs = {
        RES / "values/strings_hoard1.xml": render(en, en, singles, plurals, orders),
        # CLDR: Portuguese has one, many (large round numbers) and other; i18next writes one and other.
        RES / "values-pt-rBR/strings_hoard1.xml": render(pt, en, singles, plurals, orders, ("one", "many", "other")),
    }
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        sys.exit("stale: " + ", ".join(stale) + " (run android/scripts/strings/export_strings.py)")


if __name__ == "__main__":
    main()
