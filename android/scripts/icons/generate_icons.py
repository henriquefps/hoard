#!/usr/bin/env python3
"""Generate Phosphor icons as Compose ImageVectors (Python 3 standard library only).

Reads a list of Phosphor names (kebab-case, one per line, `#` comments), fetches the pinned @phosphor-icons/core
release (MIT) from the npm registry at generation time (never at build time) and writes PhosphorRegular.kt and
PhosphorFill.kt with only those icons (regular for everything, fill for active / selected states).

    python3 generate_icons.py --names scripts/icons/icons.txt --package dev.hfps.app.designsystem.icons \\
        --out core/designsystem/src/main/kotlin/dev/hfps/app/designsystem/icons
    python3 generate_icons.py ... --check     # CI: fail if the committed files differ

Adding an icon: append its Phosphor name (https://phosphoricons.com) to the list and run the script. Bumping
Phosphor: change VERSION (and review the diff).
"""
import argparse
import io
import sys
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "2.1.1"
URL = f"https://registry.npmjs.org/@phosphor-icons/core/-/core-{VERSION}.tgz"
HERE = Path(__file__).resolve().parent
WEIGHTS = {"regular": "Regular", "fill": "Fill"}


def pascal(name):
    return "".join(p.capitalize() for p in name.split("-"))


def fetch():
    with urllib.request.urlopen(URL, timeout=60) as r:
        data = r.read()
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def path_data(svg_text, label):
    root = ET.fromstring(svg_text)
    paths = []
    for el in root:
        tag = el.tag.split("}")[-1]
        if tag != "path":
            sys.exit(f"{label}: unsupported element <{tag}>; extend generate_icons.py")
        paths.append(el.attrib["d"])
    return paths


def render(weight, names, tar, package):
    obj = WEIGHTS[weight]
    lines = [
        f"// GENERATED by hfps-kit generate_icons.py from @phosphor-icons/core {VERSION} (MIT). Do not edit.",
        '@file:Suppress("ktlint", "MaxLineLength", "LargeClass")',
        "",
        f"package {package}",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        f"/** Phosphor {weight} weight. */",
        f"object Phosphor{obj} {{",
    ]
    for n in names:
        member = f"{n}.svg" if weight == "regular" else f"{n}-fill.svg"
        try:
            svg = tar.extractfile(f"package/assets/{weight}/{member}").read().decode()
        except KeyError:
            sys.exit(f"no Phosphor icon {weight}/{member} (check the name on phosphoricons.com)")
        p = pascal(n)
        lines.append(f"    val {p}: ImageVector by lazy {{")
        lines.append(f'        ImageVector.Builder("{obj}{p}", 24.dp, 24.dp, 256f, 256f).apply {{')
        for d in path_data(svg, member):
            lines.append("            addPath(")
            lines.append(f'                PathParser().parsePathString("{d}").toNodes(),')
            lines.append("                fill = SolidColor(Color.Black),")
            lines.append("            )")
        lines.append("        }.build()")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--names", default=str(HERE / "icons.txt"), help="icon list (default: icons.txt next to this script)")
    p.add_argument("--package", default="dev.hfps.app.designsystem.icons")
    p.add_argument("--out", default=".", help="output directory for PhosphorRegular.kt and PhosphorFill.kt")
    p.add_argument("--check", action="store_true", help="write nothing; fail if a file differs")
    args = p.parse_args()

    names = []
    for line in Path(args.names).expanduser().read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line and line not in names:
            names.append(line)
    if not names:
        sys.exit("the icon list is empty")
    tar = fetch()
    out = Path(args.out).expanduser()
    bad = False
    for weight, obj in WEIGHTS.items():
        text = render(weight, names, tar, args.package)
        target = out / f"Phosphor{obj}.kt"
        if args.check:
            if not target.exists() or target.read_text() != text:
                print(f"{target} is out of date")
                bad = True
        else:
            out.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            print(f"wrote {target} ({len(names)} icons)")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
