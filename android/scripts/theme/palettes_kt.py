#!/usr/bin/env python3
"""Writes HfpsPalettes.kt: HfpsColors for each palette x light/dark, from the generated HfpsTokens<Palette> objects
(ADR 0019). Called by generate.sh; `--check` fails when the file is stale."""
import sys
from pathlib import Path

PALETTES = ["blue", "olive", "violet", "rose", "graphite"]
OUT = Path(__file__).resolve().parents[2] / "core/designsystem/src/main/java/dev/hfps/hoard/designsystem/theme/HfpsPalettes.kt"


def colors(obj, mode, dark):
    p3 = lambda name: f"if (wideGamut) {obj}.{mode}.{name}P3 else {obj}.{mode}.{name}"
    plain = lambda name: f"{obj}.{mode}.{name}"
    fields = [
        ("background", plain("background")), ("foreground", plain("foreground")), ("card", plain("card")),
        ("cardForeground", plain("cardForeground")), ("primary", p3("primary")),
        ("primaryForeground", plain("primaryForeground")), ("secondary", plain("secondary")),
        ("secondaryForeground", plain("secondaryForeground")), ("muted", plain("muted")),
        ("mutedForeground", plain("mutedForeground")), ("accent", plain("accent")),
        ("accentForeground", plain("accentForeground")), ("destructive", plain("destructive")),
        # Light warning is outside sRGB in every palette (the generator always emits warningP3).
        ("warning", p3("warning") if not dark else plain("warning")), ("border", plain("border")),
        ("hairline", plain("border")), ("input", plain("input")), ("ring", p3("ring")),
        ("isDark", "true" if dark else "false"),
    ]
    body = "\n".join(f"        {k} = {v}," for k, v in fields)
    return f"HfpsColors(\n{body}\n    )"


def render():
    out = [
        "// GENERATED by scripts/theme/palettes_kt.py (scripts/theme/generate.sh). Do not edit.",
        "package dev.hfps.hoard.designsystem.theme",
        "",
    ]
    for p in PALETTES:
        out.append(f"import dev.hfps.hoard.designsystem.theme.tokens.HfpsTokens{p.capitalize()}")
    out += [
        "",
        "/** The hfps palettes (hfps-kit brand/palettes.css); [Blue] is the default. Ids match the web app's. */",
        "enum class HfpsPalette(val id: String) {",
    ]
    out += [f"    {p.capitalize()}(\"{p}\")," for p in PALETTES]
    out += [
        "    ;",
        "",
        "    companion object {",
        "        /** The palette with this id; [Blue] for null or an unknown id. */",
        "        fun fromId(id: String?): HfpsPalette = entries.firstOrNull { it.id == id } ?: Blue",
        "    }",
        "}",
        "",
        "/** The tokens of [palette] in light or dark, with the Display P3 variants on wide-gamut screens. */",
        "fun hfpsColors(palette: HfpsPalette, dark: Boolean, wideGamut: Boolean): HfpsColors = when (palette) {",
    ]
    for p in PALETTES:
        obj = f"HfpsTokens{p.capitalize()}"
        out.append(f"    HfpsPalette.{p.capitalize()} -> if (dark) {{")
        out.append("        " + colors(obj, "Dark", True).replace("\n", "\n    "))
        out.append("    } else {")
        out.append("        " + colors(obj, "Light", False).replace("\n", "\n    "))
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


text = render()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit(f"{OUT} is stale: run scripts/theme/generate.sh")
else:
    OUT.write_text(text)
