/**
 * Renders `src/db/migrations.ts` as Kotlin for the native importer (ADR 0019): `:core:data` brings a Capacitor
 * database older than the latest version up to it with exactly these statements before importing it.
 * `export-migrations.ts` writes the file; `src/db/nativeMigrations.test.ts` fails when it is stale.
 */
import { MIGRATIONS, type Migration } from "../../src/db/migrations"

export const KOTLIN_MIGRATIONS_PATH =
  "android/core/data/src/main/java/dev/hfps/hoard/data/legacy/LegacyMigrations.kt"

/** A Kotlin string literal with the same characters (JSON escapes are valid Kotlin; `$` is not literal there). */
function kotlinString(text: string): string {
  return JSON.stringify(text).replaceAll("$", "\\$")
}

export function renderKotlinMigrations(migrations: readonly Migration[] = MIGRATIONS): string {
  const entries = migrations
    .map(
      (m) =>
        `        LegacyMigration(\n            version = ${m.version},\n            sql = ${kotlinString(m.sql)},\n        ),`
    )
    .join("\n")
  const latest = migrations.at(-1)?.version ?? 0
  return `// GENERATED by scripts/legacy-db/export-migrations.ts from src/db/migrations.ts. Do not edit.
// Regenerate: bun scripts/legacy-db/export-migrations.ts (src/db/nativeMigrations.test.ts checks it).
package dev.hfps.hoard.data.legacy

/** One migration of the Capacitor app's database (\`src/db/migrations.ts\`), tracked by \`PRAGMA user_version\`. */
data class LegacyMigration(val version: Int, val sql: String)

/** The Capacitor app's migrations, in order. */
object LegacyMigrations {
    /** The schema version the Capacitor app's database has after its last migration. */
    const val LATEST_VERSION = ${latest}

    val ALL: List<LegacyMigration> = listOf(
${entries}
    )
}
`
}
