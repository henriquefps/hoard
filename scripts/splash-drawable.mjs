#!/usr/bin/env node
// Builds android/app/src/main/res/drawable/ic_splash.xml: the launcher foreground as a
// VectorDrawable (108dp viewport, glyph fitted exactly like build-icons.mjs does for the adaptive
// foreground), so the Android 12+ splash icon stays sharp at 240/288dp instead of upscaling the
// 108dp PNG mipmap. Rebuild it whenever scripts/glyph.svg changes, after build-icons.mjs:
//
//   NODE_PATH=<scratch>/node_modules node scripts/splash-drawable.mjs [--shape circle|square|wide|tall]
//
// (<scratch> has `npm i sharp`, same as for build-icons.mjs.)
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { pathToFileURL } from "node:url"
import { resolve } from "node:path"

const sharp = createRequire(pathToFileURL(resolve("package.json")).href)("sharp")
const FILL = { circle: 0.64, square: 0.6, wide: 0.68, tall: 0.68 }
const WHITE = "#FFFFFF"
const shapeArg = process.argv.includes("--shape")
  ? process.argv[process.argv.indexOf("--shape") + 1]
  : "auto"

const src = (await readFile("scripts/glyph.svg", "utf8")).replace(/<!--[\s\S]*?-->/g, "").trim()

// Ink box in the glyph's 128 space, strokes included (same method as build-icons.mjs).
const px = 2048
const span = 256
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-64 -64 ${span} ${span}" width="${px}" height="${px}">${src.replaceAll("currentColor", "#000")}</svg>`
const { data, info } = await sharp(Buffer.from(svg))
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true })
let x0 = px,
  y0 = px,
  x1 = -1,
  y1 = -1
for (let y = 0; y < px; y++)
  for (let x = 0; x < px; x++)
    if (data[(y * px + x) * info.channels + 3] > 24) {
      if (x < x0) x0 = x
      if (x > x1) x1 = x
      if (y < y0) y0 = y
      if (y > y1) y1 = y
    }
const u = span / px
const box = { x: x0 * u - 64, y: y0 * u - 64, w: (x1 - x0 + 1) * u, h: (y1 - y0 + 1) * u }
const r = box.w / box.h
const shape = shapeArg !== "auto" ? shapeArg : r >= 1.2 ? "wide" : r <= 0.83 ? "tall" : "square"

// Visible tile T = 72 centred in the 108 canvas (18 inset).
const s = (FILL[shape] * 72) / Math.max(box.w, box.h)
const tx = 18 + 36 - (box.x + box.w / 2) * s
const ty = 18 + 36 - (box.y + box.h / 2) * s

const paths = [...src.matchAll(/<path\b([^>]*)\/>/g)].map((m) => {
  const a = (n) => m[1].match(new RegExp(`\\s${n}="([^"]*)"`))?.[1]
  return {
    d: a("d"),
    fill: a("fill"),
    opacity: a("opacity"),
    evenodd: a("fill-rule") === "evenodd",
    sw: a("stroke-width"),
  }
})
const f = (n) => Number(n.toFixed(5)).toString()
const body = paths
  .map((p) => {
    const alpha =
      p.opacity && p.opacity !== "1" ? `\n            android:fillAlpha="${p.opacity}"` : ""
    if (p.fill && p.fill !== "none")
      return `        <path\n            android:pathData="${p.d}"\n            android:fillColor="${WHITE}"${p.evenodd ? '\n            android:fillType="evenOdd"' : ""}${alpha} />`
    return `        <path\n            android:pathData="${p.d}"\n            android:strokeColor="${WHITE}"\n            android:strokeWidth="${p.sw}"\n            android:strokeLineCap="round"\n            android:strokeLineJoin="round" />`
  })
  .join("\n")

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/splash-drawable.mjs from scripts/glyph.svg: do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="${f(tx)}"
        android:translateY="${f(ty)}"
        android:scaleX="${f(s)}"
        android:scaleY="${f(s)}">
${body}
    </group>
</vector>
`
await writeFile("android/app/src/main/res/drawable/ic_splash.xml", xml)
console.log(`ic_splash.xml: shape ${shape}, scale ${f(s)}, translate ${f(tx)} ${f(ty)}`)
